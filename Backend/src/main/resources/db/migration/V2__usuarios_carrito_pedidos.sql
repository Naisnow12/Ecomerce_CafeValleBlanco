    ('ROLE_ADMIN');


-- ============================================================
-- 2. USUARIOS
-- ============================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMP NOT NULL DEFAULT NOW()
);


-- ============================================================
-- 3. RELACIÓN USUARIOS - ROLES
-- ============================================================

CREATE TABLE usuario_roles (
    usuario_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,

    PRIMARY KEY (usuario_id, rol_id),

    CONSTRAINT fk_ur_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ur_rol
        FOREIGN KEY (rol_id)
        REFERENCES roles(id)
);


-- ============================================================
-- 4. DIRECCIONES
-- ============================================================

CREATE TABLE direcciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,

    alias VARCHAR(60),
    destinatario VARCHAR(150),

    linea1 VARCHAR(255) NOT NULL,
    linea2 VARCHAR(255),

    distrito VARCHAR(100) NOT NULL,
    provincia VARCHAR(100) NOT NULL,
    departamento VARCHAR(100) NOT NULL,

    codigo_postal VARCHAR(10),
    telefono VARCHAR(20),

    es_principal BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_dir_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_direcciones_usuario
    ON direcciones(usuario_id);


-- ============================================================
-- 5. CARRITO DE COMPRAS
-- ============================================================

CREATE TABLE carrito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id BIGINT NOT NULL UNIQUE,

    actualizado_en TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_carrito_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE CASCADE
);


-- ============================================================
-- 6. DETALLE DEL CARRITO
-- ============================================================

CREATE TABLE carrito_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    carrito_id BIGINT NOT NULL,
    precio_id BIGINT NOT NULL,

    cantidad INTEGER NOT NULL DEFAULT 1,

    CONSTRAINT chk_carrito_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT fk_ci_carrito
        FOREIGN KEY (carrito_id)
        REFERENCES carrito(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ci_precio
        FOREIGN KEY (precio_id)
        REFERENCES precios(id),

    CONSTRAINT uq_ci_carrito_precio
        UNIQUE (carrito_id, precio_id)
);

CREATE INDEX idx_carrito_items_carrito
    ON carrito_items(carrito_id);


-- ============================================================
-- 7. PEDIDOS
-- ============================================================

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    numero_pedido VARCHAR(20) NOT NULL UNIQUE,

    usuario_id BIGINT NOT NULL,

    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',

    -- Estados previstos:
    -- PENDIENTE
    -- CONFIRMADO
    -- EN_PREPARACION
    -- ENVIADO
    -- ENTREGADO
    -- CANCELADO

    -- Dirección histórica del pedido
    dir_linea1 VARCHAR(255),
    dir_linea2 VARCHAR(255),
    dir_distrito VARCHAR(100),
    dir_provincia VARCHAR(100),
    dir_departamento VARCHAR(100),
    dir_destinatario VARCHAR(150),
    dir_telefono VARCHAR(20),

    -- Totales
    subtotal NUMERIC(12,2) NOT NULL,
    costo_envio NUMERIC(10,2) NOT NULL DEFAULT 0,
    total NUMERIC(12,2) NOT NULL,

    -- Método de pago seleccionado
    metodo_pago VARCHAR(50),

    notas TEXT,

    creado_en TIMESTAMP NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_pedido_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT chk_pedido_costo_envio
        CHECK (costo_envio >= 0),

    CONSTRAINT chk_pedido_total
        CHECK (total >= 0),

    CONSTRAINT fk_pedido_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
);

CREATE INDEX idx_pedidos_usuario
    ON pedidos(usuario_id);

CREATE INDEX idx_pedidos_estado
    ON pedidos(estado);


-- ============================================================
-- 8. DETALLE DE PEDIDOS
-- ============================================================

CREATE TABLE pedido_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pedido_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,

    -- Información histórica del producto
    nombre_producto VARCHAR(255) NOT NULL,
    nombre_secundario VARCHAR(255),

    peso INTEGER NOT NULL,

    precio_unitario NUMERIC(10,2) NOT NULL,

    cantidad INTEGER NOT NULL,

    subtotal NUMERIC(12,2) NOT NULL,

    CONSTRAINT chk_pedido_item_peso
        CHECK (peso > 0),

    CONSTRAINT chk_pedido_item_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_pedido_item_precio
        CHECK (precio_unitario >= 0),

    CONSTRAINT chk_pedido_item_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT chk_pedido_item_calculo
        CHECK (subtotal = precio_unitario * cantidad),

    CONSTRAINT fk_pi_pedido
        FOREIGN KEY (pedido_id)
        REFERENCES pedidos(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_pi_producto
        FOREIGN KEY (producto_id)
        REFERENCES productos(id)
);

CREATE INDEX idx_pedido_items_pedido
    ON pedido_items(pedido_id);


-- ============================================================
-- 9. SECUENCIA PARA NÚMEROS DE PEDIDO
-- ============================================================

CREATE SEQUENCE seq_numero_pedido
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    NO CYCLE;


