-- 2. Tabla de Auditoría
CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_usuario VARCHAR(150) NOT NULL,
    rol_usuario VARCHAR(100),
    accion VARCHAR(100) NOT NULL,
    modulo VARCHAR(100) NOT NULL,
    id_registro VARCHAR(100),
    detalles TEXT,
    ip_origen VARCHAR(50),
    resultado VARCHAR(20) NOT NULL DEFAULT 'EXITO',
    creado_en TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_auditoria_usuario ON auditoria(email_usuario);
CREATE INDEX idx_auditoria_modulo ON auditoria(modulo);
CREATE INDEX idx_auditoria_creado_en ON auditoria(creado_en);

-- 3. Tabla de Movimientos de Stock
CREATE TABLE movimientos_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL, -- ENTRADA, SALIDA, AJUSTE
    cantidad INTEGER NOT NULL,
    stock_anterior INTEGER NOT NULL,
    stock_nuevo INTEGER NOT NULL,
    motivo VARCHAR(255),
    email_usuario VARCHAR(150) NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_mov_producto
        FOREIGN KEY (producto_id)
        REFERENCES productos(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_mov_stock_producto ON movimientos_stock(producto_id);
CREATE INDEX idx_mov_stock_tipo ON movimientos_stock(tipo);
CREATE INDEX idx_mov_stock_creado_en ON movimientos_stock(creado_en);

