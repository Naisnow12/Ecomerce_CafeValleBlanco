
-- V1: Esquema inicial de Cafetería Valle Blanco
-- Compatible con las entidades Product, Precio y NotaCata

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(255) NOT NULL,
    imagen_url VARCHAR(255) NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    nombre_secundario VARCHAR(255),
    tipo_cafe VARCHAR(255),
    molienda VARCHAR(255) NOT NULL,
    tueste VARCHAR(255) NOT NULL,
    variedad VARCHAR(255) NOT NULL,
    altitud VARCHAR(255) NOT NULL,
    descripcion VARCHAR(1000),
    stock INTEGER NOT NULL,
    es_destacado BOOLEAN,
    es_oscuro BOOLEAN,
    badge_text VARCHAR(255)
);

CREATE TABLE notas_cata (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL
);

CREATE TABLE precios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT,
    peso INTEGER NOT NULL,
    precio NUMERIC(10,2) NOT NULL,

    CONSTRAINT fk_precios_producto
        FOREIGN KEY (product_id)
        REFERENCES productos(id)
);

CREATE TABLE producto_notas_cata (
    producto_id BIGINT NOT NULL,
    nota_cata_id BIGINT NOT NULL,

    CONSTRAINT fk_producto_nota_producto
        FOREIGN KEY (producto_id)
        REFERENCES productos(id),

    CONSTRAINT fk_producto_nota_nota
        FOREIGN KEY (nota_cata_id)
        REFERENCES notas_cata(id)
);

CREATE INDEX idx_precios_producto
    ON precios(product_id);

CREATE INDEX idx_producto_notas_producto
    ON producto_notas_cata(producto_id);

CREATE INDEX idx_producto_notas_nota
    ON producto_notas_cata(nota_cata_id);
